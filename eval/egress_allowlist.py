"""W8, measured offline: how much would an egress allowlist break?

`docs/WEAKPOINTS.md` W8 records that sandbox egress ends in `RETURN`, so arbitrary public TCP
is allowed, and defers the fix (an egress broker) to after judging. Its acceptance asks for
"benign install success within 2 packages of today's baseline", which needs a live firewall
change and a full re-run.

This script answers the cheaper question first, from data already in the repo: the sweeps
recorded every host each package's install contacted, so the blast radius of a given allowlist
can be predicted without touching the Chamber.

**What this measures and what it does not.** A package is "at risk" if its install contacted a
host the allowlist does not cover. That is an *upper bound* on breakage, not a prediction of
it, for two reasons:

1. Many contacts are not install-critical - a telemetry ping, or an optional prebuilt binary
   with a source-build fallback. Packages that contacted a non-allowlisted host and still
   exited 0 are reported separately for that reason.
2. A *refused* connection is not the same as no connection. `REJECT` fails fast, but a
   `DROP` makes a client wait out its own timeout, so a package that tolerates refusal may
   still stall. Only a live run can settle that, which is what W8's acceptance is for.

Run: `python -m eval.egress_allowlist` (writes eval/EGRESS.md).
"""

import json
from pathlib import Path

EVAL = Path(__file__).parent

# Hosts npm's own ecosystem depends on. Splitting these from vendor CDNs is the point: T1 is
# infrastructure a Node install plausibly cannot do without, T2 is third-party endpoints where
# allowing each one is a judgement call someone has to own.
REGISTRY = frozenset({"registry.npmjs.org"})
NODE_GITHUB = frozenset({
    "nodejs.org",                            # node-gyp and friends fetching headers
    "github.com",                            # release tarballs
    "codeload.github.com",                   # the same, via the archive endpoint
    "release-assets.githubusercontent.com",  # where github.com release downloads redirect
    "api.github.com",                        # release metadata lookups
})  # fmt: skip
VENDOR_CDN = frozenset({
    "storage.googleapis.com",
    "cdn.sheetjs.com",
    "astral.sh",
    "pypi.org",  # a Python toolchain pulled in by a Node CLI wrapper
})  # fmt: skip

TIERS: tuple[tuple[str, frozenset[str]], ...] = (
    ("T0 registry only", REGISTRY),
    ("T1 + node/github release infra", REGISTRY | NODE_GITHUB),
    ("T2 + vetted vendor CDNs", REGISTRY | NODE_GITHUB | VENDOR_CDN),
)

# Hosts seen in the corpus that a curated allowlist should still refuse. Recorded explicitly
# rather than silently omitted, because "every host we happened to observe" is not an
# allowlist - someone has to decline the ones they cannot vouch for.
REFUSED = {
    "ghfast.top": "third-party GitHub mirror/accelerator of unclear provenance",
    "bl-v3-cli.oss-cn-shanghai.aliyuncs.com": "one vendor's own object store",
}


def rows(name: str) -> list[dict]:
    return json.loads((EVAL / name).read_text(encoding="utf-8"))["rows"]


def package_name(spec: str) -> str:
    """`name@version` -> `name`, preserving a leading `@scope/`."""
    at = spec.rfind("@")
    return spec[:at] if at > 0 else spec


def installed_cleanly(row: dict) -> bool:
    return row.get("exit_code") == 0 and row.get("status") == "completed"


def at_risk(corpus: list[dict], allowed: frozenset[str] | set[str]) -> list[tuple[dict, list[str]]]:
    """Packages contacting at least one host outside `allowed`, with the hosts in question."""
    out = []
    for row in corpus:
        blocked = sorted(set(row.get("hosts", [])) - set(allowed))
        if blocked:
            out.append((row, blocked))
    return out


def host_frequency(corpus: list[dict]) -> dict[str, int]:
    freq: dict[str, int] = {}
    for row in corpus:
        for host in row.get("hosts", []):
            freq[host] = freq.get(host, 0) + 1
    return freq


def _tier_of(host: str) -> str:
    if host in REFUSED:
        return "refused"
    for name, allowed in TIERS:
        if host in allowed:
            return name.split()[0]
    return "unclassified"


def report() -> str:
    big, small = rows("SWEEP500.json"), rows("SWEEP.json")
    lines = [
        "# Egress allowlist: measured blast radius (W8)",
        "",
        "Generated by `python -m eval.egress_allowlist` from the recorded sweeps. No live",
        "Chamber change is involved; see that module's docstring for what this does and does",
        "not establish.",
        "",
        f"Corpora: **{len(big)}** packages (`SWEEP500.json`) and **{len(small)}** (`SWEEP.json`).",
        "",
        "## Every host a benign install contacted",
        "",
        "| Packages | Host | Tier |",
        "|---|---|---|",
    ]
    freq = host_frequency(big)
    for host, n in sorted(freq.items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f"| {n} | `{host}` | {_tier_of(host)} |")

    lines += [
        "",
        f"All {len(big)} packages reached `registry.npmjs.org`; only "
        f"{len([r for r in big if r.get('off_registry_hosts')])} reached anything else at all.",
        "",
        "## Blast radius by tier",
        "",
        '"At risk" = contacted at least one host the tier does not allow. The second column',
        "is the subset that still exited 0, i.e. whose contact was not install-critical.",
        "",
        "| Tier | At risk (of 500) | ...which installed cleanly anyway |",
        "|---|---|---|",
    ]
    for name, allowed in TIERS:
        risky = at_risk(big, allowed)
        clean = [r for r, _ in risky if installed_cleanly(r)]
        pct = 100 * len(risky) / len(big)
        lines.append(f"| {name} | {len(risky)} ({pct:.1f}%) | {len(clean)} |")

    # The honest test: fit on one corpus, score the other.
    big_names = {package_name(r["package"]) for r in big}
    held_out = [r for r in small if package_name(r["package"]) not in big_names]
    fitted = frozenset(set(host_frequency(big)) - set(REFUSED))
    risky_held = at_risk(held_out, fitted)

    lines += [
        "",
        "## Held-out check",
        "",
        "The tiers above were read off the same corpus they were scored against, which is",
        "circular. So: fit the allowlist on the 500-package sweep only, then score the",
        f"100-package sweep. The two overlap by {len(small) - len(held_out)} package names, "
        f"leaving **{len(held_out)} genuinely unseen** packages.",
        "",
        f"Fitted allowlist ({len(fitted)} hosts, after refusing "
        f"{len(REFUSED)}): {', '.join('`' + h + '`' for h in sorted(fitted))}.",
        "",
        f"**Unseen packages needing a host outside it: {len(risky_held)}/{len(held_out)}.**",
        "",
    ]
    if risky_held:
        lines += ["| Package | Blocked host | Installed cleanly | Verdict |", "|---|---|---|---|"]
        for row, blocked in risky_held:
            lines.append(
                f"| `{row['package']}` | {', '.join('`' + b + '`' for b in blocked)} | "
                f"{installed_cleanly(row)} | {row.get('verdict', '?')} |"
            )
    lines += [
        "",
        "## Refused hosts",
        "",
        "Seen in the corpus and deliberately not allowlisted:",
        "",
    ]
    lines += [f"- `{h}` — {why}" for h, why in sorted(REFUSED.items())]
    lines += [""]
    return "\n".join(lines)


def main() -> None:
    text = report()
    (EVAL / "EGRESS.md").write_text(text, encoding="utf-8", newline="\n")
    print(text)


if __name__ == "__main__":
    main()
